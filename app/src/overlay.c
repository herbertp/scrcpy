static void
draw_char(SDL_Renderer *renderer, int x, int y, char c, int scale) {
    if (c < 32 || (unsigned char)c > 127) c = 32;
    unsigned char uc = (unsigned char)c - 32;
    for (int i = 0; i < 5; i++) {
        uint8_t line = font5x7[uc][i];
        for (int j = 0; j < 7; j++) {
            if (line & (1 << j)) {
                SDL_Rect r = {x + i * scale, y + j * scale, scale, scale};
                SDL_RenderFillRect(renderer, &r);
            }
        }
    }
}

static void
draw_text(SDL_Renderer *renderer, int x, int y, const char *text, int scale) {
    int cur_x = x;
    while (*text) {
        draw_char(renderer, cur_x, y, *text, scale);
        cur_x += 6 * scale;
        text++;
    }
}

bool
sc_overlay_init(struct sc_overlay *overlay) {
    sc_vector_init(&overlay->items);
    return sc_mutex_init(&overlay->mutex);
}

static void
sc_overlay_item_destroy(struct sc_overlay_item *item) {
    if (item->type == SC_OVERLAY_TYPE_TEXT) {
        free(item->text.text);
    }
}

void
sc_overlay_destroy(struct sc_overlay *overlay) {
    for (size_t i = 0; i < overlay->items.size; ++i) {
        sc_overlay_item_destroy(&overlay->items.data[i]);
    }
    sc_vector_destroy(&overlay->items);
    sc_mutex_destroy(&overlay->mutex);
}

void
sc_overlay_add(struct sc_overlay *overlay, const struct sc_overlay_item *item) {
    sc_mutex_lock(&overlay->mutex);
    if (!sc_vector_push(&overlay->items, *item)) {
        LOGW("Could not add overlay item");
    }
    sc_mutex_unlock(&overlay->mutex);
}

void
sc_overlay_clear(struct sc_overlay *overlay) {
    sc_mutex_lock(&overlay->mutex);
    for (size_t i = 0; i < overlay->items.size; ++i) {
        sc_overlay_item_destroy(&overlay->items.data[i]);
    }
    sc_vector_clear(&overlay->items);
    sc_mutex_unlock(&overlay->mutex);
}

static void
draw_circle(SDL_Renderer *renderer, int x0, int y0, int radius) {
    int x = radius - 1;
    int y = 0;
    int dx = 1;
    int dy = 1;
    int err = dx - (radius << 1);

    while (x >= y) {
        SDL_RenderDrawPoint(renderer, x0 + x, y0 + y);
        SDL_RenderDrawPoint(renderer, x0 + y, y0 + x);
        SDL_RenderDrawPoint(renderer, x0 - y, y0 + x);
        SDL_RenderDrawPoint(renderer, x0 - x, y0 + y);
        SDL_RenderDrawPoint(renderer, x0 - x, y0 - y);
        SDL_RenderDrawPoint(renderer, x0 - y, y0 - x);
        SDL_RenderDrawPoint(renderer, x0 + y, y0 - x);
        SDL_RenderDrawPoint(renderer, x0 + x, y0 - y);

        if (err <= 0) {
            y++;
            err += dy;
            dy += 2;
        }
        if (err > 0) {
            x--;
            dx += 2;
            err += dx - (radius << 1);
        }
    }
}

void
sc_overlay_render(struct sc_overlay *overlay, SDL_Renderer *renderer,
                  const SDL_Rect *rect) {
    if (!rect) {
        return;
    }

    sc_mutex_lock(&overlay->mutex);
    for (size_t i = 0; i < overlay->items.size; ++i) {
        struct sc_overlay_item *item = &overlay->items.data[i];
        SDL_SetRenderDrawColor(renderer, item->r, item->g, item->b, item->a);

        switch (item->type) {
            case SC_OVERLAY_TYPE_LINE: {
                int x1 = rect->x + item->line.x1 * rect->w / 10000;
                int y1 = rect->y + item->line.y1 * rect->h / 10000;
                int x2 = rect->x + item->line.x2 * rect->w / 10000;
                int y2 = rect->y + item->line.y2 * rect->h / 10000;
                SDL_RenderDrawLine(renderer, x1, y1, x2, y2);
                break;
            }
            case SC_OVERLAY_TYPE_RECT: {
                SDL_Rect r;
                r.x = rect->x + item->rect.x * rect->w / 10000;
                r.y = rect->y + item->rect.y * rect->h / 10000;
                r.w = item->rect.w * rect->w / 10000;
                r.h = item->rect.h * rect->h / 10000;
                SDL_RenderDrawRect(renderer, &r);
                break;
            }
            case SC_OVERLAY_TYPE_CIRCLE: {
                int x = rect->x + item->circle.x * rect->w / 10000;
                int y = rect->y + item->circle.y * rect->h / 10000;
                int radius = item->circle.r * rect->w / 10000; // use width for radius scale
                draw_circle(renderer, x, y, radius);
                break;
            }
            case SC_OVERLAY_TYPE_CROSS: {
                int x = rect->x + item->cross.x * rect->w / 10000;
                int y = rect->y + item->cross.y * rect->h / 10000;
                int size = item->cross.size * rect->w / 10000;
                SDL_RenderDrawLine(renderer, x - size, y, x + size, y);
                SDL_RenderDrawLine(renderer, x, y - size, x, y + size);
                break;
            }
            case SC_OVERLAY_TYPE_TEXT: {
                int x = rect->x + item->text.x * rect->w / 10000;
                int y = rect->y + item->text.y * rect->h / 10000;
                int size = item->text.size; // scale factor
                if (size <= 0) size = 1;
                draw_text(renderer, x, y, item->text.text, size);
                break;
            }
        }
    }
    sc_mutex_unlock(&overlay->mutex);
}
