static void
draw_char(SDL_Renderer *renderer, int x, int y, char c, int scale) {
    if (c < 32 || (unsigned char)c > 127) c = 32;
    unsigned char uc = (unsigned char)c - 32;
    for (int j = 0; j < 8; j++) {
        uint8_t line = font8x8[uc][j];
        for (int i = 0; i < 8; i++) {
            if (line & (1 << (7 - i))) {
                SDL_Rect r = {x + i * scale, y + j * scale, scale, scale};
                SDL_RenderFillRect(renderer, &r);
            }
        }
    }
}

static void
draw_text(SDL_Renderer *renderer, int x, int y, const char *text, int scale) {
    int cur_x = x;
    while (*text) {
        draw_char(renderer, cur_x, y, *text, scale);
        cur_x += 8 * scale;
        text++;
    }
}

static void
draw_circle(SDL_Renderer *renderer, int x0, int y0, int radius, int thickness, bool filled) {
    if (filled) {
        for (int w = 0; w < radius * 2; w++) {
            for (int h = 0; h < radius * 2; h++) {
                int dx = radius - w;
                int dy = radius - h;
                if ((dx*dx + dy*dy) <= (radius * radius)) {
                    SDL_RenderDrawPoint(renderer, x0 + dx, y0 + dy);
                }
            }
        }
        return;
    }

    for (int t = 0; t < thickness; t++) {
        int r = radius - t;
        if (r < 0) break;
        int x = r - 1;
        int y = 0;
        int dx = 1;
        int dy = 1;
        int err = dx - (r << 1);

        while (x >= y) {
            SDL_RenderDrawPoint(renderer, x0 + x, y0 + y);
            SDL_RenderDrawPoint(renderer, x0 + y, y0 + x);
            SDL_RenderDrawPoint(renderer, x0 - y, y0 + x);
            SDL_RenderDrawPoint(renderer, x0 - x, y0 + y);
            SDL_RenderDrawPoint(renderer, x0 - x, y0 - y);
            SDL_RenderDrawPoint(renderer, x0 - y, y0 - x);
            SDL_RenderDrawPoint(renderer, x0 + y, y0 - x);
            SDL_RenderDrawPoint(renderer, x0 + x, y0 - y);

            if (err <= 0) {
                y++;
                err += dy;
                dy += 2;
            }
            if (err > 0) {
                x--;
                dx += 2;
                err += dx - (r << 1);
            }
        }
    }
}

static void
draw_line_thick(SDL_Renderer *renderer, int x1, int y1, int x2, int y2, int thickness) {
    if (thickness <= 1) {
        SDL_RenderDrawLine(renderer, x1, y1, x2, y2);
        return;
    }
    float dx = x2 - x1;
    float dy = y2 - y1;
    float len = sqrtf(dx*dx + dy*dy);
    if (len < 0.0001f) return;
    float nx = -dy / len;
    float ny = dx / len;
    for (int i = 0; i < thickness; i++) {
        float offset = i - (thickness - 1) / 2.0f;
        SDL_RenderDrawLine(renderer,
            x1 + (int)(nx * offset), y1 + (int)(ny * offset),
            x2 + (int)(nx * offset), y2 + (int)(ny * offset));
    }
}

bool
sc_overlay_init(struct sc_overlay *overlay) {
    sc_vector_init(&overlay->items);
    return sc_mutex_init(&overlay->mutex);
}

static void
sc_overlay_item_destroy(struct sc_overlay_item *item) {
    if (item->type == SC_OVERLAY_TYPE_TEXT) {
        free(item->text.text);
    }
}

void
sc_overlay_destroy(struct sc_overlay *overlay) {
    for (size_t i = 0; i < overlay->items.size; ++i) {
        sc_overlay_item_destroy(&overlay->items.data[i]);
    }
    sc_vector_destroy(&overlay->items);
    sc_mutex_destroy(&overlay->mutex);
}

void
sc_overlay_add(struct sc_overlay *overlay, const struct sc_overlay_item *item) {
    sc_mutex_lock(&overlay->mutex);
    // Check if ID already exists, if so replace it
    for (size_t i = 0; i < overlay->items.size; ++i) {
        if (overlay->items.data[i].id == item->id) {
            sc_overlay_item_destroy(&overlay->items.data[i]);
            overlay->items.data[i] = *item;
            sc_mutex_unlock(&overlay->mutex);
            return;
        }
    }
    if (!sc_vector_push(&overlay->items, *item)) {
        LOGW("Could not add overlay item");
    }
    sc_mutex_unlock(&overlay->mutex);
}

void
sc_overlay_remove(struct sc_overlay *overlay, uint32_t id) {
    sc_mutex_lock(&overlay->mutex);
    for (size_t i = 0; i < overlay->items.size; ++i) {
        if (overlay->items.data[i].id == id) {
            sc_overlay_item_destroy(&overlay->items.data[i]);
            sc_vector_remove(&overlay->items, i);
            break;
        }
    }
    sc_mutex_unlock(&overlay->mutex);
}

void
sc_overlay_clear(struct sc_overlay *overlay) {
    sc_mutex_lock(&overlay->mutex);
    for (size_t i = 0; i < overlay->items.size; ++i) {
        sc_overlay_item_destroy(&overlay->items.data[i]);
    }
    sc_vector_clear(&overlay->items);
    sc_mutex_unlock(&overlay->mutex);
}

void
sc_overlay_render(struct sc_overlay *overlay, SDL_Renderer *renderer,
                  const SDL_Rect *rect) {
    if (!rect) {
        return;
    }

    sc_mutex_lock(&overlay->mutex);
    for (size_t i = 0; i < overlay->items.size; ++i) {
        struct sc_overlay_item *item = &overlay->items.data[i];
        SDL_SetRenderDrawColor(renderer, item->r, item->g, item->b, item->a);

        int thickness = item->thickness;
        if (thickness <= 0) thickness = 1;

        switch (item->type) {
            case SC_OVERLAY_TYPE_LINE: {
                int x1 = rect->x + item->line.x1 * rect->w / 10000;
                int y1 = rect->y + item->line.y1 * rect->h / 10000;
                int x2 = rect->x + item->line.x2 * rect->w / 10000;
                int y2 = rect->y + item->line.y2 * rect->h / 10000;
                draw_line_thick(renderer, x1, y1, x2, y2, thickness);
                break;
            }
            case SC_OVERLAY_TYPE_RECT: {
                int x = rect->x + item->rect.x * rect->w / 10000;
                int y = rect->y + item->rect.y * rect->h / 10000;
                int w = item->rect.w * rect->w / 10000;
                int h = item->rect.h * rect->h / 10000;
                if (item->filled) {
                    SDL_Rect r = {x, y, w, h};
                    SDL_RenderFillRect(renderer, &r);
                } else {
                    for (int t = 0; t < thickness; t++) {
                        SDL_Rect r = {x + t, y + t, w - 2*t, h - 2*t};
                        if (r.w > 0 && r.h > 0)
                            SDL_RenderDrawRect(renderer, &r);
                    }
                }
                break;
            }
            case SC_OVERLAY_TYPE_CIRCLE: {
                int x = rect->x + item->circle.x * rect->w / 10000;
                int y = rect->y + item->circle.y * rect->h / 10000;
                int radius = item->circle.r * rect->w / 10000;
                draw_circle(renderer, x, y, radius, thickness, item->filled);
                break;
            }
            case SC_OVERLAY_TYPE_CROSS: {
                int x = rect->x + item->cross.x * rect->w / 10000;
                int y = rect->y + item->cross.y * rect->h / 10000;
                int size = item->cross.size * rect->w / 10000;
                draw_line_thick(renderer, x - size, y, x + size, y, thickness);
                draw_line_thick(renderer, x, y - size, x, y + size, thickness);
                break;
            }
            case SC_OVERLAY_TYPE_TEXT: {
                int x = rect->x + item->text.x * rect->w / 10000;
                int y = rect->y + item->text.y * rect->h / 10000;
                int scale = item->text.size;
                if (scale <= 0) scale = 1;
                draw_text(renderer, x, y, item->text.text, scale);
                break;
            }
        }
    }
    sc_mutex_unlock(&overlay->mutex);
}
